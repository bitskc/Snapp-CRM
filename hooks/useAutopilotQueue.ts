import { useState, useEffect, useCallback, useRef } from 'react';
import { AutopilotAction, AutopilotQueue } from '../types';
import { useCRM } from '../contexts/CRMContext';
import { fetchLeads, addNoteToLead } from '../services/crmService';
import { generateActionQueue, generateActionContent } from '../services/geminiService';
import { preFilterLeads } from '../utils/autopilotHelpers';

const STORAGE_KEY = 'autopilot-queue';
const MAX_AGE_MS = 24 * 60 * 60 * 1000; // 24 hours

const loadFromStorage = (): AutopilotQueue | null => {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    return JSON.parse(raw) as AutopilotQueue;
  } catch {
    return null;
  }
};

const saveToStorage = (queue: AutopilotQueue) => {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(queue));
  window.dispatchEvent(new CustomEvent('autopilot-queue-updated'));
};

const isQueueValid = (queue: AutopilotQueue): boolean => {
  const age = Date.now() - new Date(queue.generatedAt).getTime();
  if (age > MAX_AGE_MS) return false;
  return queue.actions.some(a => a.status === 'pending');
};

export function useAutopilotQueue() {
  const { leads, settings, products, addToast, refreshData } = useCRM();
  const [queue, setQueue] = useState<AutopilotQueue | null>(loadFromStorage);
  const [isGenerating, setIsGenerating] = useState(false);
  const [isLoadingContent, setIsLoadingContent] = useState(false);
  const [activeActionId, setActiveActionId] = useState<string | null>(null);
  const hasAutoGenerated = useRef(false);

  // Persist queue changes to localStorage
  useEffect(() => {
    if (queue) saveToStorage(queue);
  }, [queue]);

  // Cross-tab sync
  useEffect(() => {
    const handler = (e: StorageEvent) => {
      if (e.key === STORAGE_KEY) {
        setQueue(e.newValue ? JSON.parse(e.newValue) : null);
      }
    };
    window.addEventListener('storage', handler);
    return () => window.removeEventListener('storage', handler);
  }, []);

  // Auto-generate on mount if no valid queue
  useEffect(() => {
    if (hasAutoGenerated.current) return;
    if (!settings || !leads.length) return;
    hasAutoGenerated.current = true;

    if (queue && isQueueValid(queue)) return;
    generateQueue();
  }, [settings, leads.length]); // eslint-disable-line react-hooks/exhaustive-deps

  const generateQueue = useCallback(async () => {
    if (!settings || isGenerating) return;
    setIsGenerating(true);
    try {
      // Fetch all leads (bypass context pagination)
      const { leads: allLeads } = await fetchLeads(0, 1000);
      const summaries = preFilterLeads(allLeads, settings);

      if (summaries.length === 0) {
        const emptyQueue: AutopilotQueue = {
          generatedAt: new Date().toISOString(),
          actions: [],
        };
        setQueue(emptyQueue);
        return;
      }

      const stubs = await generateActionQueue(summaries, settings, products);

      // Map stubs to full AutopilotAction with IDs
      const actions: AutopilotAction[] = stubs.map(stub => ({
        id: Math.random().toString(36).substring(2, 11),
        leadId: stub.leadId,
        leadName: stub.leadName,
        contactName: stub.contactName,
        email: stub.email,
        phone: stub.phone,
        actionType: stub.actionType,
        priority: stub.priority,
        reasoning: stub.reasoning,
        status: 'pending' as const,
      }));

      // Sort by priority descending
      actions.sort((a, b) => b.priority - a.priority);

      const newQueue: AutopilotQueue = {
        generatedAt: new Date().toISOString(),
        actions,
      };
      setQueue(newQueue);
      setActiveActionId(null);
      if (actions.length > 0) {
        addToast(`${actions.length} actions queued`, 'success');
      }
    } catch (err) {
      console.error('Error generating autopilot queue:', err);
      addToast('Failed to generate action queue', 'error');
    } finally {
      setIsGenerating(false);
    }
  }, [settings, products, isGenerating, addToast]);

  const updateAction = useCallback(
    (actionId: string, updates: Partial<AutopilotAction>) => {
      setQueue(prev => {
        if (!prev) return prev;
        return {
          ...prev,
          actions: prev.actions.map(a =>
            a.id === actionId ? { ...a, ...updates } : a
          ),
        };
      });
    },
    []
  );

  const completeAction = useCallback(
    async (actionId: string, summary: string) => {
      const action = queue?.actions.find(a => a.id === actionId);
      if (!action) return;

      updateAction(actionId, { status: 'completed' });

      try {
        await addNoteToLead(action.leadId, `Autopilot: ${summary}`);
        await refreshData();
        addToast('Action completed & logged', 'success');
      } catch (err) {
        console.error('Error logging autopilot note:', err);
        addToast('Action marked complete but note failed to save', 'error');
      }

      // Auto-advance to next pending
      const next = queue?.actions.find(
        a => a.id !== actionId && a.status === 'pending'
      );
      setActiveActionId(next?.id ?? null);
    },
    [queue, updateAction, addToast, refreshData]
  );

  const snoozeAction = useCallback(
    (actionId: string) => {
      setQueue(prev => {
        if (!prev) return prev;
        const idx = prev.actions.findIndex(a => a.id === actionId);
        if (idx === -1) return prev;
        const snoozedAction = { ...prev.actions[idx], priority: -1 };
        const remaining = prev.actions.filter((_, i) => i !== idx);
        return {
          ...prev,
          actions: [...remaining, snoozedAction],
        };
      });
      addToast('Action snoozed', 'info');
      // Advance to next
      const next = queue?.actions.find(
        a => a.id !== actionId && a.status === 'pending'
      );
      setActiveActionId(next?.id ?? null);
    },
    [queue, addToast]
  );

  const skipAction = useCallback(
    (actionId: string) => {
      updateAction(actionId, { status: 'skipped' });
    },
    [updateAction]
  );

  const loadActionContent = useCallback(
    async (actionId: string) => {
      const action = queue?.actions.find(a => a.id === actionId);
      if (!action || action.content) return;

      setIsLoadingContent(true);
      try {
        // Find the full lead from context
        const lead = leads.find(l => l.id === action.leadId);
        if (!lead) {
          addToast('Lead not found — may have been deleted', 'error');
          return;
        }
        const result = await generateActionContent(
          lead,
          action.actionType,
          settings!,
          products
        );
        const contentStr = result.subject
          ? `Subject: ${result.subject}\n\n${result.content}`
          : result.content;
        updateAction(actionId, { content: contentStr });
      } catch (err) {
        console.error('Error generating action content:', err);
        addToast('Failed to generate content', 'error');
      } finally {
        setIsLoadingContent(false);
      }
    },
    [queue, leads, settings, products, updateAction, addToast]
  );

  const startAction = useCallback(
    (actionId: string) => {
      setActiveActionId(actionId);
      const action = queue?.actions.find(a => a.id === actionId);
      if (action && !action.content) {
        loadActionContent(actionId);
      }
    },
    [queue, loadActionContent]
  );

  const regenerateContent = useCallback(
    async (actionId: string) => {
      updateAction(actionId, { content: undefined });
      await loadActionContent(actionId);
    },
    [updateAction, loadActionContent]
  );

  // Derived state
  const allActions = queue?.actions ?? [];

  // Invalidate actions for missing/status-changed leads (US-011)
  const leadIdSet = new Set(leads.map(l => l.id));
  const autopilotStatuses =
    settings?.autopilotStatuses ??
    settings?.statuses.slice(0, -1).map(s => s.id) ??
    [];

  const validatedActions = allActions.map(action => {
    if (action.status !== 'pending') return action;
    if (!leadIdSet.has(action.leadId)) {
      return { ...action, status: 'skipped' as const };
    }
    const lead = leads.find(l => l.id === action.leadId);
    if (lead && !autopilotStatuses.includes(lead.status)) {
      return { ...action, _statusChanged: true } as AutopilotAction & { _statusChanged?: boolean };
    }
    return action;
  });

  // Persist invalidated actions (missing leads marked skipped) back to queue
  useEffect(() => {
    if (!queue) return;
    const skippedIds = new Set(
      validatedActions
        .filter(a => a.status === 'skipped' && queue.actions.find(q => q.id === a.id)?.status === 'pending')
        .map(a => a.id)
    );
    if (skippedIds.size === 0) return;
    setQueue(prev => {
      if (!prev) return prev;
      return {
        ...prev,
        actions: prev.actions.map(a =>
          skippedIds.has(a.id) ? { ...a, status: 'skipped' as const } : a
        ),
      };
    });
  }, [validatedActions.length, queue?.actions.length]); // eslint-disable-line react-hooks/exhaustive-deps

  const pendingActions = validatedActions.filter(a => a.status === 'pending');
  const pendingCount = pendingActions.length;
  const completedCount = validatedActions.filter(a => a.status === 'completed').length;
  const totalCount = validatedActions.length;
  const activeAction = activeActionId
    ? validatedActions.find(a => a.id === activeActionId) ?? null
    : null;

  return {
    queue,
    actions: validatedActions,
    pendingActions,
    pendingCount,
    completedCount,
    totalCount,
    isGenerating,
    isLoadingContent,
    activeAction,
    activeActionId,
    generateQueue,
    startAction,
    completeAction,
    snoozeAction,
    skipAction,
    regenerateContent,
    setActiveActionId,
  };
}
